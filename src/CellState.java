/**
 * Enum yang merepresentasikan kemungkinan status sel dalam grid Mosaic.
 *
 * @author Vandyka
 */
public enum CellState {
    /** Status untuk sel yang dengan warna yang belum ditentukan. */
    UNKNOWN,
    /** Status untuk sel yang terisi oleh warna hitam. */
    BLACK,
    /** Status untuk sel yang terisi dengan warna putih. */
    WHITE
}
